// Открывается из «✎ править» под ответом («что где»), из пульта и командой /life guide.

let A = null;
export function initGuide(api) { A = api; }

const S = (title, rows, open = false) => `<details class="lf-guide-s"${open ? ' open' : ''}><summary>${title}</summary><div class="lf-guide-b">${rows.map(([a, b]) => `<div class="lf-guide-r"><b>${a}</b><span>${b}</span></div>`).join('')}</div></details>`;

